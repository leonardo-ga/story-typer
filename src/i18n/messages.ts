export type MessageKey = keyof typeof italian;
export const siteLanguageNames = { en: 'English', it: 'Italiano' } as const;
export type SiteLanguage = keyof typeof siteLanguageNames;

const translations: Record<
  SiteLanguage,
  Readonly<Record<MessageKey, string>> | null
> = {
  en: null, // English source messages are already the keys.
  it: italian,
};

export function isSiteLanguage(value: unknown): value is SiteLanguage {
  return typeof value === 'string' && Object.hasOwn(siteLanguageNames, value);
}

export function translate(
  language: SiteLanguage,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const message = translations[language]?.[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(values[name] ?? placeholder),
  );
}
